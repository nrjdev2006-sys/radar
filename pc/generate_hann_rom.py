#!/usr/bin/env python3
"""Generate a 1024-point Hann window as .mem and as a synthesizable Verilog ROM."""
from __future__ import annotations

import math
from pathlib import Path

N = 1024
HDL = Path(__file__).resolve().parents[1] / "hdl"
MEM = HDL / "hann_1024.mem"
VLOG = HDL / "hann_rom.v"


def coeffs() -> list[int]:
    out = []
    for n in range(N):
        w = 0.5 * (1.0 - math.cos(2.0 * math.pi * n / (N - 1)))
        out.append(max(0, min(32767, int(round(w * 32767.0)))))
    return out


def main() -> None:
    c = coeffs()
    MEM.write_text(
        "// Hann window, 1024 points, unsigned Q1.15 (0..32767)\n"
        + "\n".join(f"{v:04X}" for v in c)
        + "\n",
        encoding="utf-8",
    )

    lines = [
        "// Auto-generated by pc/generate_hann_rom.py — do not edit by hand.",
        "`timescale 1ns / 1ps",
        "module hann_rom (",
        "    input  wire [9:0]  addr,",
        "    output wire [15:0] data",
        ");",
        "    (* rom_style = \"block\" *) reg [15:0] mem [0:1023];",
        "    initial begin",
    ]
    for i, v in enumerate(c):
        lines.append(f"        mem[{i}] = 16'h{v:04X};")
    lines += [
        "    end",
        "    assign data = mem[addr];",
        "endmodule",
        "",
    ]
    VLOG.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {MEM}")
    print(f"Wrote {VLOG} ({N} coefficients)")


if __name__ == "__main__":
    main()
